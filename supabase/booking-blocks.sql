-- Gölköy Yaşam Resort - dolu tarihler (başlangıç ve bitiş günleri dahil)
create table if not exists public.booking_blocks (
  id bigint generated by default as identity primary key,
  start_date date not null,
  end_date date not null,
  created_at timestamptz not null default now(),
  constraint booking_blocks_dates_check check (end_date >= start_date)
);
create index if not exists booking_blocks_dates_idx on public.booking_blocks(start_date,end_date);
alter table public.booking_blocks enable row level security;
drop policy if exists "booking_blocks_read" on public.booking_blocks;
create policy "booking_blocks_read" on public.booking_blocks for select to anon, authenticated using (true);
drop policy if exists "booking_blocks_admin_insert" on public.booking_blocks;
create policy "booking_blocks_admin_insert" on public.booking_blocks for insert to authenticated with check (public.is_admin());
drop policy if exists "booking_blocks_admin_delete" on public.booking_blocks;
create policy "booking_blocks_admin_delete" on public.booking_blocks for delete to authenticated using (public.is_admin());
grant select on public.booking_blocks to anon, authenticated;
grant insert, delete on public.booking_blocks to authenticated;
grant usage, select on sequence public.booking_blocks_id_seq to authenticated;
